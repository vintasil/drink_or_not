# 启动语不在 LINES 里:它是设置里一段可编辑的固定文本(见 config.DEFAULTS["startup_message"]),
# 不需要随机轮换,否则用户改过的文案会被随机池盖掉。

_last = {}


def pick(kind: str) -> str:
    """随机取一条,不和上一条重复。"""
    pool = LINES[kind]
    if len(pool) == 1:
        return pool[0]
    previous = _last.get(kind)
    choices = [line for line in pool if line != previous]
    chosen = random.choice(choices)
    _last[kind] = chosen
    return chosen


def format_bubble(kind: str) -> str:
    """气泡正文,带上前面的小图标。"""
    return f"{EMOJI[kind]} {pick(kind)}"
